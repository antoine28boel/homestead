export const language = ref("en");

export function setLanguage(value) {
  language.value = value;
  document.documentElement.lang = value;
}

function texts() {
  const short = language.value.split("-")[0];
  return { ...TEXTS.en, ...(TEXTS[short] || {}) };
}

export function t(key, values = {}) {
  const text = texts()[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

export function formatDate(iso, options = { day: "numeric", month: "short" }) {
  if (!iso) return "";
  const [year, month, day] = iso.slice(0, 10).split("-").map(Number);
  return new Intl.DateTimeFormat(language.value, options).format(
    new Date(year, month - 1, day),
  );
}

export function formatAmounts(totals) {
  return Object.entries(totals || {})
    .map(([unit, quantity]) => `${Number(quantity.toFixed(2))} ${t(`unit_${unit}`)}`)
    .join(", ");
}
